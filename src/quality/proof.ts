import fs from "node:fs";
import path from "node:path";

// Proof bundle: every change comes with evidence a reviewer can trust - what
// was asked, what changed, and the result of every quality gate (tests,
// hidden acceptance tests, independent review, security gate, best-of
// scoring), plus models, spend and a pointer to the full audit trail.

export type CheckStatus = "passed" | "failed" | "warning" | "skipped";

export interface Check {
  name: string;
  status: CheckStatus;
  detail?: string;
}

export interface Proof {
  id: string;
  mode: string;
  request: string;
  models: string[];
  startedAt: string;
  durationMs: number;
  filesChanged: string[];
  linesChanged: number;
  checks: Check[];
  summary?: string;
  tokens?: number;
  costUsd?: number | null;
  tracePath?: string;
  extra?: string;
}

const ICON: Record<CheckStatus, string> = { passed: "✅", failed: "❌", warning: "⚠️", skipped: "➖" };

export function verdict(p: Proof): "verified" | "needs review" | "failed" {
  if (p.checks.some((c) => c.status === "failed")) return "failed";
  if (p.checks.some((c) => c.status === "warning") || !p.checks.some((c) => c.status === "passed")) return "needs review";
  return "verified";
}

export function renderProof(p: Proof): string {
  const v = verdict(p);
  const lines = [
    `# Proof of change: ${v === "verified" ? "✅ verified" : v === "failed" ? "❌ failed checks" : "⚠️ needs review"}`,
    "",
    `> ${p.request.replace(/\s+/g, " ").slice(0, 500)}`,
    "",
    "## Checks",
    "",
    "| Check | Result | Details |",
    "|---|---|---|",
    ...p.checks.map((c) => `| ${c.name} | ${ICON[c.status]} ${c.status} | ${(c.detail ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ").slice(0, 300)} |`),
    "",
    "## Change",
    "",
    `${p.filesChanged.length} file(s), ${p.linesChanged} line(s) changed${p.filesChanged.length ? ":" : "."}`,
    ...p.filesChanged.slice(0, 50).map((f) => `- \`${f}\``),
  ];
  if (p.summary) lines.push("", "## Agent summary", "", p.summary.trim().slice(0, 4000));
  if (p.extra) lines.push("", p.extra.trim());
  lines.push(
    "",
    "## Provenance",
    "",
    `- Mode: ${p.mode}`,
    `- Models: ${p.models.join(", ")}`,
    `- Started: ${p.startedAt}, took ${Math.round(p.durationMs / 1000)}s`,
    `- Tokens: ${p.tokens?.toLocaleString() ?? "n/a"}${p.costUsd != null ? `, estimated cost $${p.costUsd.toFixed(4)}` : ""}`,
  );
  if (p.tracePath) lines.push(`- Audit trail: \`${p.tracePath}\``);
  lines.push("", "_Generated by SwarmCode._");
  return lines.join("\n");
}

export function saveProof(root: string, p: Proof): string {
  const dir = path.join(root, ".swarmcode", "proofs");
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${p.id}.md`);
  fs.writeFileSync(file, renderProof(p));
  fs.writeFileSync(path.join(dir, `${p.id}.json`), JSON.stringify(p, null, 2));
  return path.relative(root, file).split(path.sep).join("/");
}

export function latestProof(root: string): string | undefined {
  const dir = path.join(root, ".swarmcode", "proofs");
  if (!fs.existsSync(dir)) return undefined;
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .map((f) => path.join(dir, f))
    .sort((a, b) => fs.statSync(b).mtimeMs - fs.statSync(a).mtimeMs)[0];
}
